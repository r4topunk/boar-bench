#!/usr/bin/env python3
"""In-app answer-pipeline rows (src/eval/answerEval.ts `AnswerEvalRow`, pipeline "answer") -> EvalTrace jsonl.

The same row comes from both phones: Android (`eval:device` / a request written over adb run-as) and iPhone
(`scripts/eval-iphone.mjs`, rows.jsonl or --runs-file). The base mapping is convert_legacy.from_device; this wrapper
fixes what that mapping loses on these rows (checked 2026-10-01 against a synthetic row built from the TS type):

  errors        outcome "failure" / "cancelled" / timedOut -> trace.error (legacy left it null, so a timed-out health
                item read as a memory answer and could fail the gate's health-memory rule)
  re-asks       answerAnyway writes a second row per question (answeredAnyway: true); the harness keeps the LAST
                trace per itemId, so the re-ask silently replaced the first try. Default here: the first try
                (what desktop-node does); --prefer-reask keeps the re-ask instead
  several models one file can hold several configs (answer:<modelId>); refuses to mix them unless --config picks one
  timing        receipt.prefillMs -> prefillMs, receipt.ctxTokens -> promptTokens; receipt.loadMs / cachedTokens and
                the stage marks become `other` events (kind receipt / stage / first-*)
  model swap    a generated answer whose modelId is not the config's model (the app fell back: low RAM, crashed
                load) gets error code "model-mismatch": its scores are not the requested model's
  wrong input   only rows with pipeline "answer" are accepted (a judge file also carries queryId)

Usage: python3 scorers/convert_device.py ROWS.jsonl --out T.jsonl --commit 0cfd4a77 --platform ios|android
           --host "iPhone14,5 iOS 26.6.2" [--ram-gb 4] [--arm main] [--run-id ID] [--config answer:<modelId>]
           [--build d8e83200] [--prefer-reask]
"""
import argparse, json, sys
from pathlib import Path

sys.dont_write_bytecode = True
REPO = Path(__file__).resolve().parent.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from scorers.convert_legacy import from_device, num  # noqa: E402

ADAPTER = {"ios": "ios-app", "android": "android-app"}


class DeviceRowError(ValueError):
    pass


def config_model(config_id):
    return config_id[len("answer:"):] if config_id and config_id.startswith("answer:") and config_id != "answer:current" else None


def pick_rows(rows, config=None, prefer_reask=False):
    """One row per question of one config. Returns (rows, notes)."""
    bad = [i for i, r in enumerate(rows, 1) if r.get("pipeline") != "answer" or "queryId" not in r]
    if bad:
        raise DeviceRowError(f"{len(bad)} line(s) are not answer-pipeline rows (first: line {bad[0]}); "
                             "legacy device rows go through scorers/convert_legacy.py")
    configs = sorted({r.get("configId") for r in rows})
    if config:
        rows = [r for r in rows if r.get("configId") == config]
        if not rows:
            raise DeviceRowError(f"no rows for --config {config} (file has: {', '.join(map(str, configs))})")
    elif len(configs) > 1:
        raise DeviceRowError(f"several configs in one file ({', '.join(map(str, configs))}): pick one with --config")
    first, reask = {}, {}
    for r in rows:
        (reask if r.get("answeredAnyway") else first).setdefault(r["queryId"], r)
    order = list(dict.fromkeys(r["queryId"] for r in rows))
    out, notes = [], {"reasks_dropped": 0, "reasks_kept": 0}
    for q in order:
        if prefer_reask and q in reask:
            out.append(reask[q])
            notes["reasks_kept"] += 1
        else:
            out.append(first.get(q) or reask[q])
            notes["reasks_dropped"] += q in reask and q in first
    return out, notes


def error_of_row(r):
    msg = r.get("errorMessage")
    if r.get("timedOut") or (msg and "timeout" in str(msg).lower()):
        return {"code": "timeout", "message": str(msg or "timed out")}
    if r.get("outcome") == "failure":
        return {"code": "device-failure", "message": str(msg or "outcome failure")}
    if r.get("outcome") == "cancelled":
        return {"code": "cancelled", "message": str(msg or "stopped before done")}
    want, got = config_model(r.get("configId")), r.get("modelId")
    if want and got and got != want and (num(r.get("tokensGenerated")) or 0) > 0:
        return {"code": "model-mismatch", "message": f"answer generated by {got}, config asked for {want}"}
    return None


def events_of_row(r):
    ev = []
    rec = r.get("receipt") or {}
    extra = {k: rec[k] for k in ("loadMs", "cachedTokens", "verification", "modelLabel") if rec.get(k) is not None}
    if rec.get("modelId") or r.get("modelId"):
        extra["answeredBy"] = rec.get("modelId") or r.get("modelId")
    if r.get("modelLoadMs") is not None and "loadMs" not in extra:
        extra["loadMs"] = r["modelLoadMs"]
    if extra:
        ev.append({"tMs": 0, "type": "other", "kind": "receipt", **extra})
    for s in r.get("stages") or []:
        if num(s.get("atMs")) is not None:
            ev.append({"tMs": max(0, s["atMs"]), "type": "other", "kind": "stage",
                       **{k: s[k] for k in ("stage", "tier", "index", "count") if s.get(k) is not None}})
    for key, kind in (("firstSourcesMs", "first-sources"), ("instantMs", "first-instant"),
                      ("firstTokenMs", "first-token"), ("placesMs", "first-places")):
        if num(r.get(key)) is not None:
            ev.append({"tMs": max(0, r[key]), "type": "other", "kind": kind})
    if r.get("places"):
        ev.append({"tMs": max(0, num(r.get("placesMs")) or 0), "type": "other", "kind": "places", **r["places"]})
    return sorted(ev, key=lambda e: e["tMs"])


def to_trace(r, run_id, commit, host, platform, ram_gb, arm=None, build=None):
    adapter = ADAPTER[platform]
    t = from_device(r, run_id, arm, commit, host, platform, ram_gb, adapter)
    model = r.get("modelId") or (r.get("receipt") or {}).get("modelId") or config_model(r.get("configId")) or "unknown"
    if (num(r.get("tokensGenerated")) or 0) == 0 and config_model(r.get("configId")) and model != config_model(r.get("configId")):
        # nothing generated: the receipt names a non-LLM answerer ("extractive", "places", "grounding-guard"); the
        # config's model is the system under test. The receipt's name stays in the receipt event (answeredBy).
        model = config_model(r.get("configId"))
    t["runtime"]["model"] = t["config"]["modelId"] = model
    rec = r.get("receipt") or {}
    t["timing"]["prefillMs"] = num(rec.get("prefillMs"))
    t["timing"]["promptTokens"] = num(rec.get("ctxTokens"))
    t["timing"]["retrievalMs"] = num(rec.get("retrievalMs")) if num(rec.get("retrievalMs")) is not None else num(r.get("retrievalMs"))
    v = t["runtime"]["versions"]
    v["legacy"] = "answer-eval"
    v.update({"configId": str(r.get("configId") or ""), "personality": str(r.get("personalityId") or ""),
              "maxTokens": str(r.get("maxTokens") or "")})
    if build:
        v["appBuild"] = build
    if r.get("answeredAnyway"):
        v["answeredAnyway"] = "true"
    t["error"] = error_of_row(r)
    t["events"] = events_of_row(r)
    return t


def convert_rows(rows, run_id, commit, host, platform, ram_gb=4, arm=None, config=None, build=None, prefer_reask=False):
    if not commit:
        raise DeviceRowError("device rows carry no engine commit: pass --commit")
    if platform not in ADAPTER:
        raise DeviceRowError(f"--platform must be one of {sorted(ADAPTER)}")
    picked, notes = pick_rows(rows, config, prefer_reask)
    return [to_trace(r, run_id, commit, host, platform, ram_gb, arm, build) for r in picked], notes


def convert(path, out, run_id=None, **kw):
    rows = [json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]
    traces, notes = convert_rows(rows, run_id or Path(path).stem, **kw)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("".join(json.dumps(t, ensure_ascii=False, sort_keys=True) + "\n" for t in traces), encoding="utf-8")
    return traces, notes


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input")
    ap.add_argument("--out", required=True)
    ap.add_argument("--commit", required=True, help="engine commit the app was built from (the rows carry none)")
    ap.add_argument("--platform", required=True, choices=sorted(ADAPTER))
    ap.add_argument("--host", required=True, help='e.g. "iPhone14,5 iOS 26.6.2" or "Poco F3 Android 13"')
    ap.add_argument("--ram-gb", type=float, default=4)
    ap.add_argument("--arm")
    ap.add_argument("--run-id")
    ap.add_argument("--config", help="configId to keep when the file holds several (answer:<modelId>)")
    ap.add_argument("--build", help="app build label or sha, recorded in runtime.versions.appBuild")
    ap.add_argument("--prefer-reask", action="store_true", help="keep the 'Answer anyway' re-ask instead of the first try")
    a = ap.parse_args(argv)
    try:
        ts, notes = convert(a.input, a.out, a.run_id, commit=a.commit, host=a.host, platform=a.platform, ram_gb=a.ram_gb,
                            arm=a.arm, config=a.config, build=a.build, prefer_reask=a.prefer_reask)
    except DeviceRowError as e:
        raise SystemExit(f"convert_device: {e}")
    errs = sum(t["error"] is not None for t in ts)
    print(f"wrote {len(ts)} traces -> {a.out} (errors {errs}, re-asks dropped {notes['reasks_dropped']}, "
          f"re-asks kept {notes['reasks_kept']})", file=sys.stderr)


if __name__ == "__main__":
    main()
