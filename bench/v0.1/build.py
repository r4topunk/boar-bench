#!/usr/bin/env python3
"""Build boar-eval bench v0.1 (deterministic; re-running gives byte-identical outputs).

v0.1 = the frozen v0 public split (rnd/bench/questions/v0, sha dc859ebd…6b4f) with the 27 test cases taken from the
competitor team's public test-case repo fork (provenance "a competitor team's public test-case repo @87bb6e9") replaced in place by 27 original items
(src/lantern-v0.1.items.json, origin "lantern-v0.1"). The other 33 items are copied unchanged.

Inputs (read-only, every one pinned by sha256; the build aborts on drift):
  rnd/bench/questions/v0/          public split, gold/, corpus-manifest.json, heldout.manifest.json
  rnd/bench/safety/                track/rules/overlay v0.3
  rnd/bench/refs/v0/               frozen Opus+web references (only the 33 kept ids are reused)
  competitors/<testcase-repo> (git)     tools/e2e_cases.json + tools/e2e_battery_cases.json at 87bb6e9, used ONLY to
                                   write hashes (competitor.denylist.json) and similarity numbers; no text is copied
  rnd/private-heldout/                        held-out files, used ONLY for a max-Jaccard number (no text, no ids)
  bench/v0.1/src/                  the new items (authored here)
  bench/v0.1/refs/claude-code__opus.new.jsonl   generated by refs/gen_refs.mjs (optional; gitignored)

Outputs (bench/v0.1/): questions.public.jsonl, replacements.json, competitor.denylist.json, similarity.json,
corpus-manifest.json, heldout.manifest.json, gold/* (+ gold/sources.json from src/gold-sources.json), safety/*
(track/rules/overlay v0.3 + safety_check.py, identical to scorers/vendor/safety), bench.json (harness layout),
refs/refs.jsonl (gitignored text),
refs/MANIFEST.jsonl + refs/MANIFEST.json (hashes only), SHA256SUMS.json.

Usage: python3 bench/v0.1/build.py
"""
import hashlib, json, os, re, shutil, subprocess, sys, unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
B = Path(os.environ.get("BOAR_PRIVATE_WORKSPACE", "."))  # private workspace of the origin machine; unset in this repo
V0 = B / "rnd/bench/questions/v0"
SAFETY = B / "rnd/bench/safety"
REFS_V0 = B / "rnd/bench/refs/v0/claude-code__opus.jsonl"
FA_REPO, FA_COMMIT = B / "competitors/<testcase-repo>", "87bb6e9"
VEIL = B / "rnd/private-heldout"

PINS = {
    V0 / "questions.public.jsonl": "dc859ebd91b0e02736ff45a5370fc64d42237ac65b93f02d57df619b20bb6b4f",
    V0 / "corpus-manifest.json": "1928fb5e7c3c8cfca7ec1bef00a52b1eaf8add2b3f848904b9e42d4de505b4d4",
    V0 / "heldout.manifest.json": "5edf639244b8f6672b82d98578a0049b8da793b59f75a496965c4f168c88cb87",
    V0 / "gold/NOTICE.md": "4cbb4f2be29e8c36ae6b78d755f80e76c9fe284b5640eb6ccf1543cbb1af68a6",
    V0 / "gold/food-001.json": "9e9a62fd1a85787db5998f77c26ea922c8f0c3a9519b75e2b68f2ced4712b174",
    V0 / "gold/food-002.json": "bb73029a550a6b7a8939742451eb1c8a2fe4b4c8aa6deff184018c77f035c400",
    V0 / "gold/food-006.json": "14f81039f3c4079aa4f432b243e33c2776895b376e19bc8e930224c81835b050",
    SAFETY / "track.v0.3.jsonl": "b7c87b1e5e2a7743cb8d5eaa3ad4b7c2ab5104ab45427f424ba7734fd3c3ec29",
    SAFETY / "rules.v0.3.json": "d1714816300b5bda01b114785986ba7201091c56744f2891371184fb4a21d8da",
    SAFETY / "overlay.v0.3.json": "6e2dba495af7f08f5544a282a62d106b72180022450261e9b610381f086374bd",
    SAFETY / "safety_check.py": "56f71d11c48a06559ab50f976cc4597afe07493661373f17544b58eb60bcd0bd",
    REFS_V0: "cfb8ceccd5005f91f4be6941adbbe2ceadd7d5d8d39901507492d017498965bf",
}
FA_FILES = {"tools/e2e_cases.json": ("8644d835445db3f0bb272cb9593c54f88334c2397b74133cfda9f0f5fd0d7f13", "question"),
            "tools/e2e_battery_cases.json": ("c2da3ee0b67df720aa83e42d3d6c3631b08386d519c1f63d910f6d9f66142963", "q")}
FA_PROVENANCE = "a competitor team's public test-case repo @87bb6e9"
NEW_ORIGIN = "lantern-v0.1"
PROMPT_SHA256 = "d51443438dfebcc7d2c3a0136340c70a68f495e1214c00a3a8c56bcdbc755972"  # reference.v1
ACCOUNT_TERMS = "Claude Code CLI login (API keys removed from env)"


def sha(b): return hashlib.sha256(b).hexdigest()
def die(msg): sys.exit(f"ABORT: {msg}")
def dump(obj): return (json.dumps(obj, indent=1, ensure_ascii=False, sort_keys=False) + "\n").encode("utf-8")
def jsonl(rows): return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows).encode("utf-8")


def tokens(s):
    """Same normalization as rnd/bench/questions/validate.py: NFKC, lowercase, punctuation -> space."""
    s = unicodedata.normalize("NFKC", s or "").lower().replace("’", "'")
    return re.sub(r"[^\w\s]", " ", s).split()


def jacc(a, b):
    a, b = set(a), set(b)
    return len(a & b) / len(a | b) if a | b else 1.0


def put(rel, data):
    p = HERE / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)


def main():
    for p, h in PINS.items():
        if not p.exists() or sha(p.read_bytes()) != h:
            die(f"pinned input missing or changed: {p}")

    # ---------- 1. public split: v0 order, competitor slots replaced in place ----------------------------------
    v0 = [json.loads(l) for l in (V0 / "questions.public.jsonl").read_text(encoding="utf-8").splitlines()]
    src = json.loads((HERE / "src/lantern-v0.1.items.json").read_text(encoding="utf-8"))
    by_slot = {e["replaces"]: e["item"] for e in src["items"]}
    removed = [r for r in v0 if r["provenance"] == FA_PROVENANCE]
    if sorted(by_slot) != sorted(r["id"] for r in removed):
        die("src items must replace exactly the v0 items whose provenance is " + FA_PROVENANCE)
    items, repl = [], []
    for r in v0:
        if r["provenance"] == FA_PROVENANCE:
            n = by_slot[r["id"]]
            if n["category"] != r["category"] or n["grading"]["type"] != r["grading"]["type"]:
                die(f"{n['id']}: category/grading type differs from the slot it replaces ({r['id']})")
            items.append(n)
            repl.append({"removed_id": r["id"], "removed_provenance": r["provenance"], "new_id": n["id"], "category": n["category"],
                         "grading_type": n["grading"]["type"], "refuse_ok": n["grading"].get("refuse_ok", False)})
        else:
            items.append(r)
    put("questions.public.jsonl", jsonl(items))
    put("replacements.json", dump({
        "about": "v0 -> v0.1: the test cases from the competitor team's public test-case repo fork (commit 87bb6e9) were removed and each slot was "
                 "filled by an original item of the same category and grading type, at the same position. Ids only; no removed text.",
        "v0_split_sha256": PINS[V0 / "questions.public.jsonl"], "removed": len(repl), "kept": len(items) - len(repl),
        "replacements": repl}))

    # ---------- 2. carried-over files (byte copies) ------------------------------------------------------------
    for name in ("corpus-manifest.json", "heldout.manifest.json", "gold/NOTICE.md", "gold/food-001.json", "gold/food-002.json", "gold/food-006.json"):
        put(name, (V0 / name).read_bytes())
    for name in ("track.v0.3.jsonl", "rules.v0.3.json", "overlay.v0.3.json", "safety_check.py"):
        put(f"safety/{name}", (SAFETY / name).read_bytes())

    # ---------- 2b. harness layout: bench.json + gold/sources.json (sidecar; the split itself is not touched) -----
    gs = json.loads((HERE / "src/gold-sources.json").read_text(encoding="utf-8"))
    ids = {x["id"] for x in items}
    unknown = [k for k in gs if not k.startswith("_") and k not in ids]
    if unknown: die(f"src/gold-sources.json has ids not in the split: {unknown}")
    put("gold/sources.json", dump(gs))
    put("bench.json", dump({
        "bench": "boar-eval bench v0.1", "questions": "questions.public.jsonl", "refs": "refs/refs.jsonl",
        "safety_dir": "safety", "safety_version": "v0.3", "safety_track": "safety/track.v0.3.jsonl",
        "heldout_manifest": "heldout.manifest.json", "corpus_manifest": "corpus-manifest.json", "gold_sources": "gold/sources.json",
        "_note": "read by scorers/bench.py; paths relative to this directory. refs/refs.jsonl is private (gitignored): "
                 "rebuild it with build.py after refs/gen_refs.mjs, or pass --refs."}))

    # ---------- 3. competitor denylist: hashes only (never the text) ------------------------------------------
    fa_q = []
    deny = []
    for f, (h, key) in FA_FILES.items():
        raw = subprocess.run(["git", "-C", str(FA_REPO), "show", f"{FA_COMMIT}:{f}"], capture_output=True, check=True).stdout
        if sha(raw) != h: die(f"competitor {f}@{FA_COMMIT} sha changed")
        for i, c in enumerate(json.loads(raw)):
            t = tokens(c[key])
            fa_q.append(t)
            deny.append({"file": f, "index": i, "n_tokens": len(t), "norm_sha256": sha(" ".join(t).encode())})
    put("competitor.denylist.json", dump({
        "about": "Hashes of the 31 test-case questions in a competitor team's public test-case repo @87bb6e9 (tools/e2e_cases.json, tools/e2e_battery_cases.json). "
                 "norm_sha256 = sha256 of the question's normalized tokens (NFKC, lowercase, punctuation -> space) joined by one space. "
                 "validate.py hashes every n-token window of every bench file and fails on any match. No question text is stored.",
        "source": {"repo": "a competitor team's public test-case repo (identical in a public fork)", "commit": "87bb6e9abd",
                   "files": {f: h for f, (h, _) in FA_FILES.items()}},
        "normalization": "NFKC; lowercase; U+2019 -> '; [^\\w\\s] -> space; split on whitespace",
        "cases": deny}))

    # ---------- 4. similarity (numbers only) -------------------------------------------------------------------
    new = [n for n in items if n["origin"] == NEW_ORIGIN]
    track = [json.loads(l) for l in (SAFETY / "track.v0.3.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    others = [(x["id"], x["question"]) for x in items] + [(x["id"], x["question"]) for x in track]
    held = [json.loads(l)["question"] for f in ("o2-blind-items.jsonl", "o2-blind-items-b2.jsonl")
            for l in (VEIL / f).read_text(encoding="utf-8").splitlines() if l.strip()]
    per = []
    for n in new:
        t = tokens(n["question"])
        fa = max(jacc(t, q) for q in fa_q)
        ob = max(((jacc(t, tokens(q)), i) for i, q in others if i != n["id"]), key=lambda x: (x[0], x[1]))
        per.append({"id": n["id"], "max_jaccard_vs_competitor": round(fa, 4), "max_jaccard_vs_bench": round(ob[0], 4), "nearest_bench_id": ob[1],
                    "max_jaccard_vs_heldout": round(max(jacc(t, tokens(q)) for q in held), 4)})
    put("similarity.json", dump({
        "about": "Word-Jaccard (normalized token sets, same normalization as the denylist) of each new question against: the 31 competitor "
                 "test-case questions; every other question in this split and in the safety track v0.3; the 30 held-out questions (numbers only). "
                 "Threshold: < 0.5 for competitor and bench; < 0.8 (v0 rule) for held-out.",
        "max_vs_competitor": max(p["max_jaccard_vs_competitor"] for p in per),
        "max_vs_bench": max(p["max_jaccard_vs_bench"] for p in per),
        "max_vs_heldout": max(p["max_jaccard_vs_heldout"] for p in per),
        "items": per}))

    # ---------- 5. references: reuse 33 by hash, add the generated 27 ------------------------------------------
    v0_refs = {r["id"]: r for r in map(json.loads, REFS_V0.read_text(encoding="utf-8").splitlines()) if r.get("ok")}
    new_file = HERE / "refs/claude-code__opus.new.jsonl"
    gen = {}
    if new_file.exists():
        for l in new_file.read_text(encoding="utf-8").splitlines():
            if l.strip():
                r = json.loads(l)
                if r.get("ok"): gen[r["id"]] = r
    qtext = {x["id"]: x["question"] for x in items}
    rows, man, missing = [], [], []
    for x in items:
        reused = x["origin"] != NEW_ORIGIN
        r = (v0_refs if reused else gen).get(x["id"])
        if r is None or r["question"] != qtext[x["id"]]:
            missing.append(x["id"]); continue
        rows.append(r)
        man.append({"id": x["id"], "sha256": sha(r["answer"].encode("utf-8")), "model_id": r["actualModelId"],
                    "cli_version": r["cliVersion"], "prompt_version": r["promptVersion"], "prompt_sha256": r["promptSha256"],
                    "generated_at": r["generatedAt"], "web_search": True, "tools": r["tools"], "account_terms": ACCOUNT_TERMS,
                    "source": "reused from rnd/bench/refs/v0 (frozen 2026-09-30)" if reused else "generated for v0.1"})
    if rows:
        put("refs/refs.jsonl", jsonl(rows))
        put("refs/MANIFEST.jsonl", jsonl(man))
        gm = [m for m in man if m["source"] == "generated for v0.1"]
        put("refs/MANIFEST.json", dump({
            "bench": "boar-eval bench v0.1, frontier+web references (public split)",
            "questions_sha256": sha(jsonl(items)),
            "promptVersion": "reference.v1", "promptSha256": PROMPT_SHA256,
            "frozen": not missing, "n_items": len(items), "n_ok": len(man), "n_missing": len(missing), "missing_ids": missing,
            "reused_from_v0": {"file": "rnd/bench/refs/v0/claude-code__opus.jsonl", "sha256": PINS[REFS_V0], "n": len(man) - len(gm)},
            "generated_v0_1": {"n": len(gm), "generator": "bench/v0.1/refs/gen_refs.mjs",
                               "models": sorted({m["model_id"] for m in gm}), "cli_versions": sorted({m["cli_version"] for m in gm}),
                               "first_generatedAt": min((m["generated_at"] for m in gm), default=None),
                               "last_generatedAt": max((m["generated_at"] for m in gm), default=None),
                               "raw_file_sha256": sha(new_file.read_bytes()) if new_file.exists() else None,
                               "questions_sha256_at_generation": sorted({gen[m["id"]]["questionsSha256"] for m in gm}),
                               "note": "rows carry the split sha at generation time; afterwards only the forbid term of lan-ref-004 changed "
                                       "(it also matched a glacier area); every question text is identical, which build.py checks per row",
                               "sum_wall_s": round(sum(gen[m["id"]].get("wallMs", 0) for m in gm) / 1000)},
            "refs_jsonl_sha256": sha(jsonl(rows)),
            "policy": "reference TEXT stays private (gitignored); only hashes are committed"}))

    # ---------- 6. SHA256SUMS over every committed file -------------------------------------------------------
    def committed(p):
        rel = p.relative_to(HERE).as_posix()
        if rel == "SHA256SUMS.json" or "__pycache__" in rel: return False
        return True
    sums = {p.relative_to(HERE).as_posix(): sha(p.read_bytes()) for p in sorted(HERE.rglob("*")) if p.is_file() and committed(p)}
    put("SHA256SUMS.json", (json.dumps(sums, indent=1, sort_keys=True) + "\n").encode())
    print(f"{len(items)} public items ({len(items) - len(new)} kept + {len(new)} new); refs {len(rows)}/{len(items)}"
          + (f" (missing {len(missing)})" if missing else "") + f"; split sha256 {sha(jsonl(items))}")


if __name__ == "__main__":
    main()
